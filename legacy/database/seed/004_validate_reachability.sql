SET HEADING ON FEEDBACK ON
WITH statuses AS (
    SELECT 'REQUESTED' s FROM dual UNION ALL SELECT 'ELIGIBLE' FROM dual UNION ALL
    SELECT 'MANUAL_REVIEW' FROM dual UNION ALL SELECT 'ALLOCATING' FROM dual UNION ALL
    SELECT 'AWAITING_ACTIVATION' FROM dual
)
SELECT s AS stranded_status FROM statuses
 WHERE NOT EXISTS (SELECT 1 FROM na_workflow_branches WHERE status = s);
EXIT;
